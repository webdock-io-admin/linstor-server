package com.linbit.linstor.layer.drbd.utils;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.Paths;
import java.util.Arrays;
import java.util.Collections;

import org.junit.Rule;
import org.junit.Test;
import org.junit.rules.TemporaryFolder;

import static org.junit.Assert.assertEquals;
import static org.junit.Assert.assertFalse;
import static org.junit.Assert.assertTrue;

public class DrbdAdmScopedConfTest
{
    @Rule
    public TemporaryFolder tmpDir = new TemporaryFolder();

    @Test
    public void includesGlobalCommonThenTheResFilesInOrder()
    {
        String content = DrbdAdmScopedConf.buildContent(
            Paths.get("/etc/drbd.d/global_common.conf"),
            Arrays.asList(Paths.get("/var/lib/linstor.d/b.res"), Paths.get("/var/lib/linstor.d/a.res"))
        );
        assertEquals(
            """
                # generated by LINSTOR for one drbdadm call, deleted afterwards
                include "/etc/drbd.d/global_common.conf";
                include "/var/lib/linstor.d/b.res";
                include "/var/lib/linstor.d/a.res";
                """,
            content
        );
    }

    @Test
    public void withoutGlobalCommonOnlyTheResFiles()
    {
        String content = DrbdAdmScopedConf.buildContent(
            null,
            Collections.singletonList(Paths.get("/var/lib/linstor.d/a.res"))
        );
        assertFalse(content.contains("global_common"));
        assertTrue(content.endsWith("include \"/var/lib/linstor.d/a.res\";\n"));
    }

    @Test
    public void resFileIsTheLinstorResourceFile()
    {
        assertEquals(Paths.get("/var/lib/linstor.d/rsc.res"), DrbdAdmScopedConf.resFile("rsc"));
    }

    @Test
    public void createWritesTheFileAndCloseDeletesIt() throws IOException
    {
        Path dir = tmpDir.getRoot().toPath().resolve("scoped");
        Path globalCommon = tmpDir.newFile("global_common.conf").toPath();
        Path resFile = tmpDir.newFile("rsc.res").toPath();

        Path confFile;
        try (DrbdAdmScopedConf conf = DrbdAdmScopedConf.create(dir, globalCommon, Collections.singletonList(resFile)))
        {
            confFile = conf.getPath();
            assertEquals(dir, confFile.getParent());
            assertTrue(DrbdAdmScopedConf.isScopedConfName(confFile.getFileName().toString()));
            assertFalse(DrbdAdmScopedConf.isScopedConfName("rsc.res"));
            String content = new String(Files.readAllBytes(confFile), StandardCharsets.UTF_8);
            assertTrue(content.contains("include \"" + globalCommon.toAbsolutePath() + "\";"));
            assertTrue(content.contains("include \"" + resFile.toAbsolutePath() + "\";"));
        }
        assertFalse(Files.exists(confFile));
    }

    @Test
    public void createSkipsAMissingGlobalCommon() throws IOException
    {
        Path dir = tmpDir.getRoot().toPath().resolve("scoped");
        Path missing = tmpDir.getRoot().toPath().resolve("no-such-global_common.conf");
        Path resFile = tmpDir.newFile("rsc.res").toPath();

        try (DrbdAdmScopedConf conf = DrbdAdmScopedConf.create(dir, missing, Collections.singletonList(resFile)))
        {
            String content = new String(Files.readAllBytes(conf.getPath()), StandardCharsets.UTF_8);
            assertFalse(content.contains("no-such-global_common.conf"));
        }
    }

    @Test
    public void twoConcurrentConfsGetDifferentFiles() throws IOException
    {
        Path dir = tmpDir.getRoot().toPath().resolve("scoped");
        Path resFile = tmpDir.newFile("rsc.res").toPath();
        try (
            DrbdAdmScopedConf first = DrbdAdmScopedConf.create(dir, resFile, Collections.singletonList(resFile));
            DrbdAdmScopedConf second = DrbdAdmScopedConf.create(dir, resFile, Collections.singletonList(resFile))
        )
        {
            assertFalse(first.getPath().equals(second.getPath()));
        }
    }

    @Test
    public void standardLayoutIsRecognised() throws IOException
    {
        Path drbdD = tmpDir.newFolder("drbd.d").toPath();
        Files.write(drbdD.resolve("global_common.conf"), new byte[0]);
        Files.write(drbdD.resolve("linstor-resources.res"), new byte[0]);
        Path drbdConf = writeDrbdConf(
            """
            # You can find an example in  /usr/share/doc/drbd.../drbd.conf.example

            include "drbd.d/global_common.conf";
            include  "drbd.d/*.res";
            """
        );
        assertTrue(DrbdAdmScopedConf.isStandardLayout(drbdConf, drbdD));

        Files.write(drbdD.resolve("other.res"), new byte[0]);
        assertFalse(DrbdAdmScopedConf.isStandardLayout(drbdConf, drbdD));
    }

    @Test
    public void extraContentInDrbdConfIsNotStandard() throws IOException
    {
        Path drbdD = tmpDir.newFolder("drbd.d").toPath();
        assertFalse(
            DrbdAdmScopedConf.isStandardLayout(
                writeDrbdConf(
                    """
                    include "drbd.d/global_common.conf";
                    include "drbd.d/*.res";
                    common { options { auto-promote yes; } }
                    """
                ),
                drbdD
            )
        );
        assertFalse(
            DrbdAdmScopedConf.isStandardLayout(
                writeDrbdConf("include \"drbd.d/global_common.conf\";\ninclude \"/etc/drbd.d/global_common.conf\";\n"),
                drbdD
            )
        );
        assertFalse(DrbdAdmScopedConf.isStandardLayout(tmpDir.getRoot().toPath().resolve("missing.conf"), drbdD));
    }

    private Path writeDrbdConf(String content) throws IOException
    {
        Path drbdConf = tmpDir.getRoot().toPath().resolve("drbd.conf");
        Files.write(drbdConf, content.getBytes(StandardCharsets.UTF_8));
        return drbdConf;
    }
}
